def is_code_or_identifier(token: str) -> bool:
    """Returns whether `token` is a code identifier, number, or acronym."""
    if not token or len(token) <= 2:
        return True
    if any(ch.isdigit() or ch == "_" for ch in token):
        return True
    return bool(_IDENTIFIER_RE.match(token) or token == "CODE_IDENT")


